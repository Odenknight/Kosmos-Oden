fn main() {
    // `generate_context!` requires a PNG even when bundling is disabled. Keep the
    // placeholder generated and untracked until production branding is approved.
    const INTERNAL_ALPHA_PNG: &[u8] = &[
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44,
        0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f,
        0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x78, 0xda, 0x63, 0xfc,
        0xcf, 0xc0, 0x50, 0x0f, 0x00, 0x05, 0x83, 0x02, 0x7f, 0x95, 0x9d, 0xe3, 0x00, 0x00, 0x00,
        0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ];
    let icon_dir =
        std::path::PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap()).join("icons");
    std::fs::create_dir_all(&icon_dir).expect("failed to create generated icon directory");
    std::fs::write(icon_dir.join("icon.png"), INTERNAL_ALPHA_PNG)
        .expect("failed to write internal-alpha PNG");

    #[cfg(target_os = "windows")]
    {
        // A deterministic one-pixel emerald ICO is sufficient for the internal-alpha
        // executable resource. Production branding remains an explicit release gate.
        const INTERNAL_ALPHA_ICON: &[u8] = &[
            0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00,
            0x30, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x28, 0x00, 0x00, 0x00, 0x01, 0x00,
            0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x6b, 0xe5, 0xc0, 0xff, 0x00, 0x00, 0x00, 0x00,
        ];
        let icon = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap())
            .join("internal-alpha.ico");
        std::fs::write(&icon, INTERNAL_ALPHA_ICON).expect("failed to write internal-alpha icon");
        let attributes = tauri_build::Attributes::new()
            .windows_attributes(tauri_build::WindowsAttributes::new().window_icon_path(icon));
        tauri_build::try_build(attributes).expect("failed to run Tauri build script");
    }
    #[cfg(not(target_os = "windows"))]
    tauri_build::build();
}
