/**
 * Personal Notes (0.9.5) — pure, deterministic Map-of-Content (MoC) generator.
 *
 * Given the notes of ONE folder, produces the exact Markdown of a generated
 * index note. No Obsidian, Node or engine imports; no clock, no randomness,
 * no locale: the same input (in any order) gives byte-identical output.
 *
 * Contract
 * - Folder: a valid vault-relative path. The vault root ("" or "/") is
 *   rejected in this version.
 * - Listed: notes (paths ending in ".md", any case) that are direct children
 *   of the folder, or any descendant when `recursive`. Other supplied paths
 *   are ignored. Never listed: the target itself and any file whose base name
 *   (case-insensitive, without ".md") is index, _index, readme, moc or
 *   contents. More than `maxNotes` listed notes is an error, never a
 *   truncation.
 * - Order: by sort key = display title, NFC-normalised then lower-cased with
 *   the locale-independent String.prototype.toLowerCase, compared by UTF-16
 *   code units; ties break on the exact path, also by code units. Subfolder
 *   groups (recursive) are ordered segment by segment with the same rule.
 * - Display title: `title` with every run of whitespace/control characters
 *   collapsed to one space and trimmed; the base name when that is empty.
 * - Links (first that applies):
 *     1. `[[Base name]]`         the base name is unique (case-insensitively)
 *                                among ALL supplied note paths, equals the
 *                                display title, and is wikilink-safe;
 *     2. `[[folder/path|Title]]` path without ".md"; target and title are
 *                                wikilink-safe;
 *     3. `[Title](folder/path.md)` Markdown link, when the target contains one
 *                                of | # ^ [ ] or the title one of | [ ] \ <.
 *                                The title is backslash-escaped and the path
 *                                percent-encoded, so nothing is dropped or
 *                                substituted. Newlines never occur: paths with
 *                                control characters are rejected and titles
 *                                are collapsed to one line.
 * - Summaries and headings are emitted as plain text (Markdown punctuation is
 *   backslash-escaped); summaries are single-lined and capped at
 *   MOC_SUMMARY_MAX_CHARS code points.
 * - File layout: optional user text, then one MANAGED BLOCK between the exact
 *   lines MOC_BEGIN_MARKER and MOC_END_MARKER. Only the block is ever
 *   replaced; every byte outside it is preserved. New files use LF; updates
 *   use the existing file's dominant line ending (CRLF only when CRLF lines
 *   outnumber LF lines) and keep its BOM.
 * - A file without a block is never adopted ("unmanaged_file"); malformed
 *   markers refuse with a specific reason. Marker lines inside fenced code
 *   blocks (``` or ~~~, indented at most three spaces) or inside closed
 *   leading frontmatter do not count.
 *
 * `aliases`, `tags` and `updatedAt` are accepted so callers can pass note
 * metadata as is; version 1 of the layout does not render them.
 */
import { isUnderFolder, vaultPathProblem } from "./scope";

export const MOC_CONTRACT = "kosmos-moc/1";
export const MOC_BEGIN_MARKER = "<!-- kosmos-moc:begin v1 -->";
export const MOC_END_MARKER = "<!-- kosmos-moc:end -->";
export const MOC_NOTICE = "_Generated by Kosmos. Do not edit between these markers; changes here are overwritten._";
export const MOC_EMPTY_LINE = "_No notes._";
export const MOC_SUPERSEDED_HEADING = "Superseded";
export const MOC_DEFAULT_FILE_NAME = "index.md";
export const MOC_DEFAULT_MAX_NOTES = 2000;
export const MOC_SUMMARY_MAX_CHARS = 240;
/** Base names (lower case, without ".md") that are never listed as entries. */
export const MOC_INDEX_BASENAMES: readonly string[] = Object.freeze(["index", "_index", "readme", "moc", "contents"]);

export type MocErrorCode = "invalid_folder" | "invalid_option" | "invalid_note" | "too_many_notes";

export class MocError extends Error {
  readonly code: MocErrorCode;
  constructor(code: MocErrorCode, message: string) {
    super(message);
    this.name = "MocError";
    this.code = code;
  }
}

export interface MocNoteInput {
  path: string;
  title?: string | null;
  aliases?: readonly string[];
  tags?: readonly string[];
  updatedAt?: string | null;
  supersededBy?: readonly string[] | null;
  summary?: string | null;
}

export interface MocOptions {
  /** File name of the index note inside the folder. Default "index.md". */
  fileName?: string;
  /** Include notes in subfolders, grouped under one heading per subfolder. Default false. */
  recursive?: boolean;
  /** Keep superseded notes in the main list instead of the trailing "Superseded" section. Default false. */
  includeSuperseded?: boolean;
  /** Heading of a newly created index note. Default: the folder's base name. */
  title?: string;
  /** Refuse (MocError "too_many_notes") above this many listed notes. Default 2000. */
  maxNotes?: number;
}

export type MocLinkForm = "short" | "path" | "markdown";

export interface MocEntry {
  path: string;
  /** Display title. */
  title: string;
  /** Subfolder relative to the MoC folder; "" for direct children. */
  group: string;
  /** True when the note is listed in the "Superseded" section. */
  superseded: boolean;
  form: MocLinkForm;
  /** Link target as a reader of the block recovers it: base name (short) or path without ".md". */
  target: string;
  /** The exact bullet line. */
  line: string;
}

export interface MocBlock {
  folder: string;
  /** Vault path of the index note. */
  target: string;
  /** Resolved heading title for a new file. */
  title: string;
  /** Managed block, markers included, LF line endings, no trailing newline. */
  block: string;
  entries: readonly MocEntry[];
}

export type MocAction = "create" | "update" | "unchanged" | "refuse";
export type MocRefuseReason =
  | "unmanaged_file"
  | "begin_without_end"
  | "end_without_begin"
  | "end_before_begin"
  | "multiple_blocks"
  | "unknown_version"
  | "malformed_marker"
  | "too_many_notes";

export interface MocPlan {
  contract: typeof MOC_CONTRACT;
  folder: string;
  target: string;
  action: MocAction;
  reason?: MocRefuseReason;
  /** Human-readable detail for a refusal. */
  detail?: string;
  /** The exact text the plan was computed from; null when the file did not exist. */
  existingRaw: string | null;
  /** Full new file text; equals existingRaw for "unchanged"; null for "refuse". */
  proposedRaw: string | null;
  entries: readonly MocEntry[];
  /** Paths of entries that have no link in the existing managed block. */
  added: readonly string[];
  /** Link targets (base name or path without ".md") in the existing block that match no entry. */
  removed: readonly string[];
}

/* ------------------------------------------------------------------ helpers */

const MD_EXT = /\.md$/i;

/** Code-unit comparison; never locale-dependent. */
function compareCodeUnits(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** The documented sort normalisation: NFC, then locale-independent lower case. */
export function mocSortKey(text: string): string {
  return text.normalize("NFC").toLowerCase();
}

// eslint-disable-next-line no-control-regex
const WHITESPACE_RUN = /[\s\u0000-\u001f\u007f-\u009f\u2028\u2029]+/g;

function singleLine(text: unknown): string {
  return typeof text === "string" ? text.replace(WHITESPACE_RUN, " ").trim() : "";
}

/** Backslash-escape Markdown/Obsidian punctuation so the text renders literally. */
function escapeInline(text: string): string {
  return text.replace(/[\\`*_[\]<>#~=$%|^&]/g, "\\$&");
}

function baseNameOf(path: string): string {
  return path.slice(path.lastIndexOf("/") + 1).replace(MD_EXT, "");
}

function encodeLinkPath(path: string): string {
  return path.split("/").map((segment) => encodeURIComponent(segment).replace(/[()!'*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`)).join("/");
}

function truncateCodePoints(text: string, max: number): string {
  const points = Array.from(text);
  return points.length <= max ? text : `${points.slice(0, max - 1).join("").trimEnd()}…`;
}

function deepFreeze<T>(value: T): T {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const key of Object.keys(value as object)) deepFreeze((value as Record<string, unknown>)[key]);
  }
  return value;
}

interface ResolvedOptions { fileName: string; recursive: boolean; includeSuperseded: boolean; title: string; maxNotes: number }

function requireMocFolder(folder: unknown): string {
  if (folder === "" || folder === "/") throw new MocError("invalid_folder", "the vault root cannot have a generated index in this version");
  const problem = vaultPathProblem(folder);
  if (problem) throw new MocError("invalid_folder", `folder is not a valid vault-relative path (${problem})`);
  return folder as string;
}

function resolveOptions(folder: string, options: MocOptions | undefined): ResolvedOptions {
  const o = options ?? {};
  const fileName = o.fileName === undefined ? MOC_DEFAULT_FILE_NAME : o.fileName;
  if (vaultPathProblem(fileName) || fileName.includes("/") || !MD_EXT.test(fileName) || fileName.length <= 3) {
    throw new MocError("invalid_option", "fileName must be a single file name ending in .md");
  }
  const maxNotes = o.maxNotes === undefined ? MOC_DEFAULT_MAX_NOTES : o.maxNotes;
  if (typeof maxNotes !== "number" || !Number.isInteger(maxNotes) || maxNotes < 1) throw new MocError("invalid_option", "maxNotes must be a positive integer");
  if (o.title !== undefined && typeof o.title !== "string") throw new MocError("invalid_option", "title must be a string");
  const title = singleLine(o.title) || folder.slice(folder.lastIndexOf("/") + 1);
  return { fileName, recursive: o.recursive === true, includeSuperseded: o.includeSuperseded === true, title, maxNotes };
}

function isSuperseded(note: MocNoteInput): boolean {
  return Array.isArray(note.supersededBy) && note.supersededBy.some((value) => typeof value === "string" && value.trim() !== "");
}

function compareGroups(a: string, b: string): number {
  const left = a.split("/"), right = b.split("/");
  for (let i = 0; i < Math.min(left.length, right.length); i++) {
    const byKey = compareCodeUnits(mocSortKey(left[i]), mocSortKey(right[i])) || compareCodeUnits(left[i], right[i]);
    if (byKey) return byKey;
  }
  return left.length - right.length;
}

const WIKI_TARGET_UNSAFE = /[|#^[\]]/;
const WIKI_TITLE_UNSAFE = /[|[\]\\<]/;

/* -------------------------------------------------------------------- build */

/** Build the managed block and its ordered entries. Throws MocError on invalid input or above maxNotes. */
export function buildMocBlock(input: { folder: string; notes: readonly MocNoteInput[]; options?: MocOptions }): MocBlock {
  const folder = requireMocFolder(input?.folder);
  const options = resolveOptions(folder, input.options);
  if (!Array.isArray(input.notes)) throw new MocError("invalid_note", "notes must be a list");
  const target = `${folder}/${options.fileName}`;

  // Validate every supplied note and count base names over the whole input.
  const seen = new Set<string>();
  const baseCount = new Map<string, number>();
  const candidates: MocNoteInput[] = [];
  for (const note of input.notes as readonly MocNoteInput[]) {
    const path = note?.path;
    const problem = vaultPathProblem(path);
    if (problem) throw new MocError("invalid_note", `note path is not a valid vault-relative path (${problem})`);
    if (seen.has(path)) throw new MocError("invalid_note", `note path is listed twice: ${path}`);
    seen.add(path);
    if (!MD_EXT.test(path)) continue;
    const baseKey = mocSortKey(baseNameOf(path));
    baseCount.set(baseKey, (baseCount.get(baseKey) ?? 0) + 1);
    if (path === target || MOC_INDEX_BASENAMES.includes(baseNameOf(path).toLowerCase())) continue;
    if (!isUnderFolder(path, folder) || path === folder) continue;
    const relative = path.slice(folder.length + 1);
    if (!options.recursive && relative.includes("/")) continue;
    candidates.push(note);
  }
  if (candidates.length > options.maxNotes) {
    throw new MocError("too_many_notes", `${candidates.length} notes exceed the limit of ${options.maxNotes}; nothing was generated`);
  }

  const drafts = candidates.map((note) => {
    const path = note.path;
    const base = baseNameOf(path);
    const title = singleLine(note.title) || singleLine(base) || base;
    const relative = path.slice(folder.length + 1);
    const group = relative.includes("/") ? relative.slice(0, relative.lastIndexOf("/")) : "";
    const pathNoExt = path.replace(MD_EXT, "");
    let form: MocLinkForm, link: string, linkTarget = pathNoExt;
    if (WIKI_TARGET_UNSAFE.test(pathNoExt) || WIKI_TITLE_UNSAFE.test(title)) {
      form = "markdown";
      link = `[${escapeInline(title)}](${encodeLinkPath(path)})`;
    } else if (title === base && baseCount.get(mocSortKey(base)) === 1) {
      form = "short"; linkTarget = base;
      link = `[[${base}]]`;
    } else {
      form = "path";
      link = `[[${pathNoExt}|${title}]]`;
    }
    const summary = truncateCodePoints(singleLine(note.summary), MOC_SUMMARY_MAX_CHARS);
    const line = `- ${link}${summary ? ` - ${escapeInline(summary)}` : ""}`;
    const entry: MocEntry = { path, title, group, superseded: !options.includeSuperseded && isSuperseded(note), form, target: linkTarget, line };
    return { entry, key: mocSortKey(title) };
  });
  const byTitle = (a: typeof drafts[number], b: typeof drafts[number]) => compareCodeUnits(a.key, b.key) || compareCodeUnits(a.entry.path, b.entry.path);
  drafts.sort((a, b) =>
    Number(a.entry.superseded) - Number(b.entry.superseded)
    || (a.entry.superseded ? 0 : Number(a.entry.group !== "") - Number(b.entry.group !== "") || compareGroups(a.entry.group, b.entry.group))
    || byTitle(a, b));
  const entries = drafts.map((draft) => draft.entry);

  const lines: string[] = [MOC_BEGIN_MARKER, MOC_NOTICE, ""];
  if (!entries.length) lines.push(MOC_EMPTY_LINE);
  let section: string | null = null; // "" = direct children, "g:<group>" or "superseded"
  for (const entry of entries) {
    const next = entry.superseded ? "superseded" : entry.group ? `g:${entry.group}` : "";
    if (next !== section) {
      if (next !== "") {
        if (section !== null) lines.push("");
        lines.push(`## ${entry.superseded ? MOC_SUPERSEDED_HEADING : escapeInline(entry.group)}`, "");
      }
      section = next;
    }
    lines.push(entry.line);
  }
  lines.push(MOC_END_MARKER);
  return deepFreeze({ folder, target, title: options.title, block: lines.join("\n"), entries });
}

/* --------------------------------------------------------------------- scan */

interface MarkerHit { kind: "begin" | "end" | "unknown_version" | "malformed"; start: number; end: number }

/** Marker lines of `body` (no BOM), skipping fenced code blocks and closed leading frontmatter. */
function scanMarkers(body: string): MarkerHit[] {
  const lineSpans: { start: number; end: number }[] = [];
  const eol = /\r\n|\n/g;
  let start = 0;
  for (let match = eol.exec(body); match; match = eol.exec(body)) {
    lineSpans.push({ start, end: match.index });
    start = match.index + match[0].length;
  }
  lineSpans.push({ start, end: body.length });
  const text = (i: number) => body.slice(lineSpans[i].start, lineSpans[i].end);

  let first = 0;
  if (/^---[ \t]*$/.test(text(0))) {
    for (let i = 1; i < lineSpans.length; i++) {
      if (/^---[ \t]*$/.test(text(i))) { first = i + 1; break; }
    }
  }
  const hits: MarkerHit[] = [];
  let fence: { char: string; length: number } | null = null;
  for (let i = first; i < lineSpans.length; i++) {
    const line = text(i);
    if (fence) {
      const close = /^ {0,3}(`{3,}|~{3,})[ \t]*$/.exec(line);
      if (close && close[1][0] === fence.char && close[1].length >= fence.length) fence = null;
      continue;
    }
    const open = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line);
    if (open && !(open[1][0] === "`" && open[2].includes("`"))) {
      fence = { char: open[1][0], length: open[1].length };
      continue;
    }
    if (!/^[ \t]*<!--[ \t]*kosmos-moc:/i.test(line)) continue;
    const kind = line === MOC_BEGIN_MARKER ? "begin"
      : line === MOC_END_MARKER ? "end"
      : /^<!-- kosmos-moc:begin \S+ -->$/.test(line) ? "unknown_version"
      : "malformed";
    hits.push({ kind, ...lineSpans[i] });
  }
  return hits;
}

type BlockLocation = { ok: true; start: number; end: number } | { ok: false; reason: MocRefuseReason; detail: string };

function locateBlock(body: string): BlockLocation {
  const hits = scanMarkers(body);
  const refuse = (reason: MocRefuseReason, detail: string): BlockLocation => ({ ok: false, reason, detail });
  if (!hits.length) return refuse("unmanaged_file", "the file has no Kosmos managed block; it was not adopted");
  if (hits.some((hit) => hit.kind === "unknown_version")) return refuse("unknown_version", "the managed block was written by a different layout version");
  if (hits.some((hit) => hit.kind === "malformed")) return refuse("malformed_marker", "a marker line is not exactly as generated");
  let open: MarkerHit | null = null, block: { start: number; end: number } | null = null, blocks = 0;
  for (let i = 0; i < hits.length; i++) {
    const hit = hits[i];
    if (hit.kind === "begin") {
      if (open) return refuse("begin_without_end", "a begin marker is not followed by an end marker");
      open = hit;
    } else if (!open) {
      const laterBegin = blocks === 0 && hits.slice(i + 1).some((other) => other.kind === "begin");
      return laterBegin ? refuse("end_before_begin", "an end marker comes before the begin marker") : refuse("end_without_begin", "an end marker has no begin marker");
    } else {
      block = { start: open.start, end: hit.end };
      open = null;
      blocks++;
    }
  }
  if (open) return refuse("begin_without_end", "a begin marker is not followed by an end marker");
  if (blocks !== 1 || !block) return refuse("multiple_blocks", "the file has more than one managed block");
  return { ok: true, start: block.start, end: block.end };
}

/** Link targets (base name or path without ".md") of the bullets in a managed block, in order, deduplicated. */
export function readMocBlockLinks(block: string): string[] {
  const out: string[] = [];
  for (const line of block.split(/\r\n|\n/)) {
    const wiki = /^- \[\[([^\]]*?)\]\]/.exec(line);
    const md = wiki ? null : /^- \[(?:\\.|[^\]\\])*\]\(([^)\s]*)\)/.exec(line);
    let target: string | null = null;
    if (wiki) target = wiki[1].split("|")[0];
    else if (md) {
      try { target = decodeURIComponent(md[1]).replace(MD_EXT, ""); } catch { target = md[1]; }
    }
    if (target && !out.includes(target)) out.push(target);
  }
  return out;
}

function dominantEol(text: string): "\r\n" | "\n" {
  const crlf = (text.match(/\r\n/g) ?? []).length;
  const lf = (text.match(/\n/g) ?? []).length - crlf;
  return crlf > lf ? "\r\n" : "\n";
}

/* --------------------------------------------------------------------- plan */

/**
 * Plan the index note for one folder. Pure: nothing is read or written.
 * Invalid input throws MocError; exceeding maxNotes and every problem with
 * the existing file yield a frozen plan with action "refuse".
 */
export function planMoc(input: { folder: string; notes: readonly MocNoteInput[]; existingRaw: string | null; options?: MocOptions }): MocPlan {
  const existingRaw = input?.existingRaw ?? null;
  if (existingRaw !== null && typeof existingRaw !== "string") throw new MocError("invalid_option", "existingRaw must be a string or null");
  let built: MocBlock;
  try {
    built = buildMocBlock(input);
  } catch (error) {
    if (!(error instanceof MocError) || error.code !== "too_many_notes") throw error;
    const folder = requireMocFolder(input.folder);
    const target = `${folder}/${resolveOptions(folder, input.options).fileName}`;
    return deepFreeze<MocPlan>({ contract: MOC_CONTRACT, folder, target, action: "refuse", reason: "too_many_notes", detail: error.message, existingRaw, proposedRaw: null, entries: [], added: [], removed: [] });
  }
  const { folder, target, entries } = built;
  const base = { contract: MOC_CONTRACT, folder, target, existingRaw, entries } as const;

  if (existingRaw === null) {
    const proposedRaw = `# ${escapeInline(built.title)}\n\n${built.block}\n`;
    return deepFreeze<MocPlan>({ ...base, action: "create", proposedRaw, added: entries.map((entry) => entry.path), removed: [] });
  }

  const bom = existingRaw.startsWith("\uFEFF") ? "\uFEFF" : "";
  const body = existingRaw.slice(bom.length);
  const located = locateBlock(body);
  if (located.ok === false) {
    return deepFreeze<MocPlan>({ ...base, action: "refuse", reason: located.reason, detail: located.detail, proposedRaw: null, added: [], removed: [] });
  }
  const eol = dominantEol(body);
  const block = eol === "\n" ? built.block : built.block.split("\n").join(eol);
  const proposedRaw = bom + body.slice(0, located.start) + block + body.slice(located.end);

  // Diff against the links of the existing block. A short link matches the one entry with that base name.
  const oldTargets = readMocBlockLinks(body.slice(located.start, located.end));
  const matched = new Set<string>();
  const removed: string[] = [];
  for (const oldTarget of oldTargets) {
    const hits = oldTarget.includes("/")
      ? entries.filter((entry) => entry.path.replace(MD_EXT, "") === oldTarget)
      : entries.filter((entry) => baseNameOf(entry.path) === oldTarget);
    if (hits.length === 1) matched.add(hits[0].path);
    else removed.push(oldTarget);
  }
  const added = entries.filter((entry) => !matched.has(entry.path)).map((entry) => entry.path);
  // Removed targets in code-unit order, so the list does not depend on the old block's layout.
  removed.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  return deepFreeze<MocPlan>({ ...base, action: proposedRaw === existingRaw ? "unchanged" : "update", proposedRaw, added, removed });
}
